DIRECTIVE_PATTERNS = [
    # JS / TS
    r"eslint-(?:disable|enable|env)", r"\beslint\s*\{", r"jshint\b", r"jslint\b",
    r"tslint:", r"stylelint-(?:disable|enable)", r"jscs:",
    r"@ts-\w+", r"@flow\b", r"\$FlowFixMe", r"@jsx\b",
    r"prettier-ignore", r"biome-ignore", r"dprint-ignore", r"rome-ignore",
    r"deno-lint-ignore", r"oxlint-disable", r"@formatter:(?:off|on)",
    r"webpack\w+:", r"@vite-ignore", r"vite-ignore",
    r"istanbul ignore", r"\bc8 ignore", r"\bv8 ignore", r"coverage:ignore",
    r"sourceMappingURL", r"sourceURL=",
    # Python
    r"\bnoqa\b", r"type:\s*ignore", r"pylint:", r"mypy:", r"pyright:", r"\bruff:",
    r"flake8:", r"isort:", r"fmt:\s*(?:on|off|skip)", r"yapf:", r"\bnosec\b",
    r"bandit:", r"pragma:\s*no\s*cover", r"noinspection",
    # C / C++ / C# / Java / Swift
    r"#\s*pragma\b", r"#\s*(?:region|endregion)\b", r"\bNOLINT",
    r"clang-format\s+(?:on|off)", r"checkstyle:", r"SuppressWarnings",
    r"@SuppressLint", r"sonar\.", r"NOSONAR",
    r"swiftlint:", r"@formatter",
    # Go
    r"go:(?:build|generate|embed|linkname|noinline|nosplit)", r"^\s*//\s*\+build",
    r"\bnolint\b",
    # Ruby / PHP
    r"rubocop:", r"frozen_string_literal:", r"typed:\s*\w+",
    r"phpcs:", r"@phpstan-", r"@psalm-", r"psalm-", r"codingStandardsIgnore",
    r"@codeCoverageIgnore",
    # Shell / infra / sécurité
    r"shellcheck\s+disable", r"hadolint\b", r"yamllint\b", r"gitleaks:allow",
    r"nosemgrep", r"trivy:ignore", r"tflint-ignore", r"checkov:skip",
    r"ansible-lint", r"kics-scan",
    # Éditeurs / fichiers générés
    r"vim:\s*set", r"-\*-\s*\w+", r"DO NOT EDIT", r"@generated\b", r"auto-?generated",
    r"Code generated by",
]
DIRECTIVE_RE = re.compile("|".join(DIRECTIVE_PATTERNS), re.I | re.M)

LICENSE_RE = re.compile(
    r"SPDX-License-Identifier|copyright|\(c\)\s*\d{4}|licen[cs]ed?\b|"
    r"all rights reserved|@license|@preserve|GNU General Public|MIT License|"
    r"Apache License",
    re.I,
)

MARKER_RE = re.compile(
    r"\b(TODO|FIXME|HACK|XXX|BUG|NOTE|OPTIMIZE|REVIEW|REFACTOR|DEPRECATED|WARNING|"
    r"IMPORTANT|CAUTION|SAFETY|SECURITY)\b"
)
MARKER_LOWER_RE = re.compile(r"\b(todo|fixme|hack|bug)\s*[:(\[]", re.I)

HEADER_ZONE_LINES = 8


@dataclass
class Protections:
    directives: bool = True
    headers: bool = True
    markers: bool = True
    docs: bool = True

    @classmethod
    def from_args(cls, args):
        return cls(
            directives=not getattr(args, "include_directives", False),
            headers=not getattr(args, "include_headers", False),
            markers=not getattr(args, "no_keep_todo", False),
            docs=not getattr(args, "include_docstrings", False),
        )


def protection_reason(c: Comment, prot: Protections) -> str:
    if prot.directives:
        if c.text.startswith("#!") and c.line == 1:
            return "shebang"
        if c.text.startswith("/*!"):
            return "directive (bloc préservé par les minifieurs)"
        if DIRECTIVE_RE.search(c.text):
            m = DIRECTIVE_RE.search(c.text)
            return f"directive outil ({m.group(0).strip()})"
    if prot.headers and c.line <= HEADER_ZONE_LINES and LICENSE_RE.search(c.text):
        return "en-tête licence/copyright"
    if prot.markers and (MARKER_RE.search(c.text) or MARKER_LOWER_RE.search(c.text)):
        m = MARKER_RE.search(c.text) or MARKER_LOWER_RE.search(c.text)
        return f"marqueur {m.group(1).upper()}"
    if prot.docs and (c.doc or c.kind == "docstring"):
        return "documentation d'API"
    return ""


def classify(comments: List[Comment], prot: Protections) -> List[Comment]:
    for c in comments:
        c.protected = protection_reason(c, prot) or None
        c.ai_score, c.ai_reasons = ai_score(c)
    return comments


