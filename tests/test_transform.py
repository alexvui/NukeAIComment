class TestBackup(unittest.TestCase):
    def setUp(self):
        from nukeai.guards import Backup

        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.a, self.b = self.tmp / "a.ts", self.tmp / "b.ts"
        self.a.write_text("un\n", encoding="utf-8")
        self.b.write_text("deux\n", encoding="utf-8")
        self.backup = Backup(self.tmp)
        self.backup.save(self.a)
        self.backup.save(self.b)
        self.addCleanup(shutil.rmtree, self.backup.slot, ignore_errors=True)
        self.a.write_text("MODIFIÉ\n", encoding="utf-8")
        self.b.write_text("MODIFIÉ\n", encoding="utf-8")

    def test_selective_rollback_touches_only_the_named_file(self):
        self.assertEqual(self.backup.rollback([self.a]), 1)
        self.assertEqual(self.a.read_text(), "un\n")
        self.assertEqual(self.b.read_text(), "MODIFIÉ\n")

    def test_full_rollback_restores_everything(self):
        self.assertEqual(self.backup.rollback(), 2)
        self.assertEqual(self.b.read_text(), "deux\n")


class TestCli(unittest.TestCase):
    def run_cli(self, *args, cwd=None):
        entry = Path(__file__).parent.parent / "scripts" / "nukeaicomment.py"
        return subprocess.run([sys.executable, str(entry), *args],
                              capture_output=True, text=True, cwd=cwd)

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        (self.tmp / "a.ts").write_text(
            "// Initialize the counter to zero\nlet counter = 0;\n", encoding="utf-8")
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def test_dry_run_does_not_write(self):
        before = (self.tmp / "a.ts").read_text()
        out = self.run_cli("nuke", "a.ts", "--no-color", cwd=self.tmp)
        self.assertEqual(out.returncode, 0)
        self.assertIn("simulation", out.stdout)
        self.assertEqual((self.tmp / "a.ts").read_text(), before)

    def test_apply_writes_and_backs_up(self):
        out = self.run_cli("nuke", "a.ts", "--apply", "--no-color", "-q", cwd=self.tmp)
        self.assertEqual(out.returncode, 0, out.stdout + out.stderr)
        self.assertEqual((self.tmp / "a.ts").read_text(), "let counter = 0;\n")
        self.assertIn("sauvegarde", out.stdout)

    def test_restore_brings_the_file_back(self):
        self.run_cli("nuke", "a.ts", "--apply", "--no-color", "-q", cwd=self.tmp)
        out = self.run_cli("restore", "--no-color", cwd=self.tmp)
        self.assertEqual(out.returncode, 0, out.stdout)
        self.assertIn("Initialize the counter", (self.tmp / "a.ts").read_text())

    def test_scan_json_output(self):
        out = self.run_cli("scan", "a.ts", "--json", cwd=self.tmp)
        data = json.loads(out.stdout)
        self.assertEqual(data["stats"]["comments"], 1)

    def test_plan_then_apply(self):
        plan_path = self.tmp / "plan.json"
        out = self.run_cli("humanize", "a.ts", "-o", str(plan_path), "--no-color",
                           cwd=self.tmp)
        self.assertEqual(out.returncode, 0, out.stdout + out.stderr)
        plan = json.loads(plan_path.read_text())
        plan["items"][0]["new_text"] = ["compteur remis à zéro à chaque cycle"]
        plan_path.write_text(json.dumps(plan), encoding="utf-8")
        out = self.run_cli("apply-plan", str(plan_path), "--apply", "--no-color", "-q",
                           cwd=self.tmp)
        self.assertEqual(out.returncode, 0, out.stdout + out.stderr)
        self.assertIn("// compteur remis à zéro", (self.tmp / "a.ts").read_text())


